// Turn a build plus a brain into files you can run: a Pybricks program for
// the hub, and for the modes brain a laptop bridge that asks Jev. The hub
// side follows Pybricks' documented stdin/stdout pattern; the bridge follows
// its "Hub to PC communication" tutorial (Nordic UART over the Pybricks
// command characteristic, 0x01 = stdout event, 0x06 = write stdin).
import { HUBS, DEVICES } from './catalog.js';
import { sensorPort } from './build.js';
import { MODES, jevRequest, facts } from './brain.js';
import { MODE_CODES, TELEOP } from './link.js';

const PY_COLOR = { black: 'BLACK', white: 'WHITE', red: 'RED', green: 'GREEN', blue: 'BLUE', yellow: 'YELLOW' };
const num = (v) => (Number.isFinite(Number(v)) ? String(Math.round(Number(v) * 100) / 100) : '0');
const pyPort = (p) => `Port.${p}`;

function header(build) {
  const hub = HUBS[build.hub];
  const devs = new Set(Object.values(build.ports).filter(Boolean).map((d) => DEVICES[d].pybricks));
  const lines = [];
  if (build.hub === 'ev3') lines.push('#!/usr/bin/env pybricks-micropython');
  lines.push(`# Generated by Botbench for the ${hub.name} (${hub.kit}). Check every port against your build.`);
  lines.push(`from pybricks.hubs import ${hub.pybricksHub}`);
  lines.push(`from ${hub.pybricksDevices} import ${[...devs].sort().join(', ')}`);
  lines.push('from pybricks.parameters import Port, Direction, Color');
  lines.push('from pybricks.tools import wait, StopWatch');
  lines.push('');
  lines.push(`hub = ${hub.pybricksHub}()`);
  // The Pybricks DriveBase example mounts the left motor mirrored, hence
  // COUNTERCLOCKWISE. Flip it if your robot spins instead of driving forward.
  lines.push(`left = Motor(${pyPort(build.left)}, Direction.COUNTERCLOCKWISE)`);
  lines.push(`right = Motor(${pyPort(build.right)})`);
  for (const [port, d] of Object.entries(build.ports)) {
    if (!d || port === build.left || port === build.right) continue;
    const dev = DEVICES[d];
    const name = dev.kind === 'motor' ? `aux_${port.toLowerCase()}` : { color: 'color', distance: 'eyes', touch: 'bumper' }[dev.sense];
    if (dev.kind !== 'motor' && sensorPort(build, dev.sense) !== port) continue;
    lines.push(`${name} = ${dev.pybricks}(${pyPort(port)})`);
  }
  lines.push('');
  lines.push('MAX_DEG_S = 900  # the simulator uses the same scale: 100 % = 900 deg/s');
  lines.push('');
  lines.push('def drive(l, r):');
  lines.push('    left.run(l * MAX_DEG_S / 100)');
  lines.push('    right.run(r * MAX_DEG_S / 100)');
  lines.push('');
  lines.push('def halt():');
  lines.push('    left.stop()');
  lines.push('    right.stop()');
  lines.push('');
  const distDev = sensorPort(build, 'distance') && DEVICES[build.ports[sensorPort(build, 'distance')]];
  if (distDev) {
    lines.push('def distance_mm():');
    lines.push(distDev.pybricks === 'InfraredSensor'
      ? '    return eyes.distance() * 7  # IR reports relative 0-100; about 7 mm per unit, calibrate on your floor'
      : '    return eyes.distance()');
    lines.push('');
  }
  return lines;
}

function condition(rule) {
  if (rule.sensor === 'always') return 'True';
  if (rule.sensor === 'distance') return `distance_mm() ${rule.op} ${num(rule.value)}`;
  if (rule.sensor === 'reflection') return `color.reflection() ${rule.op} ${num(rule.value)}`;
  if (rule.sensor === 'color') return `color.color() == Color.${PY_COLOR[rule.value] || 'RED'}`;
  if (rule.sensor === 'touch') return rule.value === 'pressed' ? 'bumper.pressed()' : 'not bumper.pressed()';
  return 'False';
}

function actionBody(rule) {
  if (rule.action === 'stop') return ['    halt()'];
  if (rule.action === 'line') {
    return [
      `    error = color.reflection() - ${num(rule.target)}`,
      `    turn = ${num(rule.kp)} * error`,
      `    drive(${num(rule.base)} + turn * 0.5, ${num(rule.base)} - turn * 0.5)`,
    ];
  }
  return [`    drive(${num(rule.left)}, ${num(rule.right)})`];
}

function missingSensors(build, rules) {
  const need = new Set(rules.map((r) => (r.sensor === 'reflection' ? 'color' : r.sensor)).filter((s) => s !== 'always'));
  if (rules.some((r) => r.action === 'line')) need.add('color');
  return [...need].filter((s) => !sensorPort(build, s));
}

/** Pybricks program for a rule table. */
export function rulesProgram(build, rules) {
  const lines = header(build);
  const missing = missingSensors(build, rules);
  if (missing.length) lines.push(`# WARNING: rules read ${missing.join(', ')} but no such sensor is in the build.`, '');
  rules.forEach((r, i) => {
    lines.push(`def rule_${i}():`);
    lines.push(...actionBody(r));
    lines.push('');
  });
  lines.push('watch = StopWatch()');
  lines.push('held = None');
  lines.push('held_until = 0');
  lines.push('');
  lines.push('while True:');
  lines.push('    now = watch.time()');
  lines.push('    if held is not None and now < held_until:');
  lines.push('        held()');
  lines.push('    else:');
  lines.push('        held = None');
  rules.forEach((r, i) => {
    lines.push(`        ${i === 0 ? 'if' : 'elif'} ${condition(r)}:`);
    lines.push(`            rule_${i}()`);
    if (Number(r.holdMs) > 0) lines.push(`            held = rule_${i}`, `            held_until = now + ${num(r.holdMs)}`);
  });
  if (!rules.length) lines.push('        halt()');
  else lines.push('        else:', '            halt()');
  lines.push('    wait(10)');
  return lines.join('\n') + '\n';
}

const CODE = MODE_CODES;

function factsFn(build) {
  const L = ['def facts_line():'];
  L.push(sensorPort(build, 'distance')
    ? '    d = distance_mm()\n    front = "blocked" if d < 160 else ("obstacle near" if d < 420 else "clear")'
    : '    front = "no distance sensor"');
  L.push(sensorPort(build, 'color')
    ? '    global crossed\n    r = color.reflection()\n    if color.color() == Color.RED:\n        floor = "red zone"\n    elif r < 35:\n        floor = "dark line"\n    elif r < 65:\n        floor = "line edge"\n    elif crossed:\n        floor = "crossed a line"\n    else:\n        floor = "plain floor"\n    crossed = False'
    : '    floor = "no colour sensor"');
  L.push(sensorPort(build, 'touch')
    ? '    bump = "pressed" if bumper.pressed() else "not pressed"'
    : '    bump = "no touch sensor"');
  L.push('    return "front=" + front + ";floor=" + floor + ";bumper=" + bump + ";mode=" + mode_name + "\\n"');
  L.push('');
  return L;
}

/**
 * Hub program for the modes brain: reports facts twice a second, takes a
 * mode letter or a teleop digit on stdin. The Link tab and bridge.py both
 * speak to this program; the virtual hub in the simulator imitates it.
 */
export function modesProgram(build) {
  const lines = header(build);
  if (build.hub === 'ev3') {
    lines.push('# The EV3 path: this brick has no Bluetooth LE, so neither the Link tab');
    lines.push('# nor bridge.py can reach it. It prints facts so you can watch them in');
    lines.push('# Pybricks Code or over SSH, and picks modes with the hub buttons.', '');
    lines.push('from pybricks.parameters import Button', '');
  } else {
    lines.push('from usys import stdin, stdout');
    lines.push('from uselect import poll', '');
    lines.push('keyboard = poll()');
    lines.push('keyboard.register(stdin)', '');
  }
  lines.push(...factsFn(build));
  for (const [k, m] of Object.entries(MODES)) {
    lines.push(`def mode_${k}():`);
    lines.push(...actionBody(m.rules[0]));
    lines.push('');
  }
  lines.push('def mode_teleop():');
  lines.push('    drive(teleop[0], teleop[1])');
  lines.push('');
  lines.push(`CODES = {${Object.entries(CODE).map(([k, c]) => `b"${c}": (mode_${k}, "${k}")`).join(', ')}}`);
  lines.push(`TELEOP = {${Object.entries(TELEOP).map(([d, t]) => `b"${d}": (${t.drive[0]}, ${t.drive[1]})`).join(', ')}}`);
  lines.push('run_mode, mode_name = mode_explore, "explore"');
  lines.push('teleop = (0, 0)');
  lines.push('crossed = False  # latched between reports: a thin line passes in a tenth of a second');
  lines.push('watch = StopWatch()');
  lines.push('next_report = 0', '');
  lines.push('while True:');
  lines.push('    now = watch.time()');
  lines.push('    if now >= next_report:');
  lines.push(build.hub === 'ev3' ? '        print(facts_line(), end="")' : '        stdout.buffer.write(facts_line().encode())');
  lines.push('        next_report = now + 500');
  if (build.hub !== 'ev3') {
    lines.push('    if keyboard.poll(0):');
    lines.push('        key = stdin.buffer.read(1)');
    lines.push('        if key in CODES:');
    lines.push('            run_mode, mode_name = CODES[key]');
    lines.push('        elif key in TELEOP:');
    lines.push('            teleop = TELEOP[key]');
    lines.push('            run_mode, mode_name = mode_teleop, "teleop"');
  } else {
    lines.push('    pressed = hub.buttons.pressed()');
    lines.push('    if Button.LEFT in pressed:');
    lines.push('        run_mode, mode_name = mode_follow_line, "follow_line"');
    lines.push('    elif Button.RIGHT in pressed:');
    lines.push('        run_mode, mode_name = mode_explore, "explore"');
    lines.push('    elif Button.DOWN in pressed:');
    lines.push('        run_mode, mode_name = mode_stop, "stop"');
  }
  if (sensorPort(build, 'color')) {
    lines.push('    if color.reflection() < 65:');
    lines.push('        crossed = True');
  }
  lines.push('    run_mode()');
  lines.push('    wait(10)');
  return lines.join('\n') + '\n';
}

/** Laptop bridge: BLE to the hub, HTTPS to Jev, confidence-gated mode switch. */
export function bridgeScript(goal, gateMin) {
  const sample = jevRequest(goal, facts({ distance: 900, reflection: 80, color: 'white', touch: false }, 'explore', 0));
  const criteria = JSON.stringify(sample.questions.mode.criteria, null, 4).replace(/\n/g, '\n    ');
  return `# Botbench bridge: Inventor Hub (Pybricks) <-> laptop <-> TypeSafe Jev.
# pip install bleak        Requires Pybricks firmware >= 3.3 on the hub.
# export TYPESAFE_API_KEY=...   The key stays on this machine, never on the hub
# or in a web page. Usage: python bridge.py ["your goal"] [--dry-run]
import asyncio, json, os, sys, time, urllib.request
from contextlib import suppress
from bleak import BleakScanner, BleakClient

PYBRICKS_COMMAND_EVENT_CHAR_UUID = "c5f50002-8280-46da-89f4-6d8051e4aeef"
HUB_NAME = "Pybricks Hub"
API = "https://api.typesafe.ai/v1/systemone"
GOAL = next((a for a in sys.argv[1:] if not a.startswith("--")), ${JSON.stringify(goal)})
DRY_RUN = "--dry-run" in sys.argv
MIN_CONFIDENCE = ${num(gateMin)}
CODES = ${JSON.stringify(CODE)}
CRITERIA = ${criteria}


def ask_jev(robot):
    body = {
        "model": "jev-latest",
        "state": {"goal": GOAL, "robot": robot},
        "questions": {
            "mode": {
                "type": "choice",
                "instructions": "Which behaviour should the robot run next to make progress on \`goal\`, given \`robot\`?",
                "criteria": CRITERIA,
            },
            "goal_reached": {"type": "noul", "instructions": "Has the robot achieved \`goal\`?"},
        },
    }
    if DRY_RUN:
        print(json.dumps(body, indent=2))
        return None
    req = urllib.request.Request(API, data=json.dumps(body).encode(), method="POST", headers={
        "Authorization": "Bearer " + os.environ["TYPESAFE_API_KEY"],
        "Content-Type": "application/json",
    })
    with urllib.request.urlopen(req, timeout=5) as resp:
        return json.load(resp)["answers"]


def bucket(seconds):
    return "just started" if seconds < 2 else ("a few seconds" if seconds < 8 else "a long time")


async def main():
    mode, since, buf = "explore", time.monotonic(), b""
    lines = asyncio.Queue()

    def handle_rx(_, data):
        nonlocal buf
        if data[0] == 0x01:  # stdout event from the hub
            buf += data[1:]
            while b"\\n" in buf:
                line, buf = buf.split(b"\\n", 1)
                lines.put_nowait(line.decode())

    device = await BleakScanner.find_device_by_name(HUB_NAME)
    if device is None:
        sys.exit("Hub not found. Disconnect Pybricks Code and make sure no program is running.")
    async with BleakClient(device) as client:
        await client.start_notify(PYBRICKS_COMMAND_EVENT_CHAR_UUID, handle_rx)
        try:  # start the program the hub holds (profile 1.2+); fails harmlessly if it is already running
            await client.write_gatt_char(PYBRICKS_COMMAND_EVENT_CHAR_UUID, b"\\x01", response=True)
        except Exception:
            pass
        print("Connected. If the program did not start, press the hub button.")
        while True:
            line = await lines.get()
            while not lines.empty():  # act on the freshest facts only
                line = lines.get_nowait()
            robot = dict(kv.split("=", 1) for kv in line.split(";") if "=" in kv)
            reported = robot.pop("mode", None)  # the hub's own word on what it is running
            if reported and reported != mode:
                mode, since = reported, time.monotonic()
            robot["current_mode"] = mode
            robot["time_in_mode"] = bucket(time.monotonic() - since)
            answers = await asyncio.to_thread(ask_jev, robot)
            if not answers:
                continue
            pick = answers["mode"]
            print(robot, "->", pick["choice"], round(pick["confidence"], 2), "done=%.2f" % answers["goal_reached"]["noul"])
            if pick["confidence"] >= MIN_CONFIDENCE and pick["choice"] != mode:
                mode, since = pick["choice"], time.monotonic()
                await client.write_gatt_char(PYBRICKS_COMMAND_EVENT_CHAR_UUID, b"\\x06" + CODES[mode].encode(), response=True)


if __name__ == "__main__":
    with suppress(asyncio.CancelledError, KeyboardInterrupt):
        asyncio.run(main())
`;
}
